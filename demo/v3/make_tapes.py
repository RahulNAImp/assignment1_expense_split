"""vhs tapes for demo v3, timed to the narration beats.

Commands appear as a paste (no typing animation); `hold` is how long the output stays on screen
before the next step, chosen so each output appears when the voice talks about it.
"""

from pathlib import Path

HERE = Path(__file__).parent
HEAD = '''# generated by demo/v3/make_tapes.py - real commands recorded with charmbracelet/vhs
Output demo/v3/build/{name}.mp4
Set Shell "bash"
Set FontSize 22
Set Width 1920
Set Height 1080
Set Padding 40
Set Theme "Catppuccin Mocha"
Hide
Type "cd {cd} && source .venv/bin/activate && export PYTHONPATH=src PS1='$ ' PYTHONWARNINGS=ignore {extra}&& clear" Enter
Sleep 1s
Show
'''


def tape(name, cd, steps, extra=""):
    out = HEAD.format(name=name, cd=cd, extra=extra)
    for step in steps:
        kind = step[0]
        if kind == "sleep":
            out += f"Sleep {step[1]}\n"
        elif kind == "clear":
            out += 'Hide\nType "clear" Enter\nSleep 200ms\nShow\n'
        elif kind == "wait":
            out += f"Wait+Screen@60s /{step[1]}/\n"
        else:  # ("paste", cmd, hold)
            _, cmd, hold = step
            q = "`" if '"' in cmd else '"'
            out += f"Type@1ms {q}{cmd}{q}\nSleep 500ms\nEnter\nSleep {hold}\n"
    (HERE / "tapes" / f"{name}.tape").write_text(out)


