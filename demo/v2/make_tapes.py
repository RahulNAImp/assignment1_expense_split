"""Generate the vhs tapes (screen recordings of real commands) for demo video v2."""

from pathlib import Path

HERE = Path(__file__).parent
PASTE_OVER = 60  # characters; longer commands are "pasted", shorter ones are typed (~65 ms/key)
HEAD = '''# generated by demo/v2/make_tapes.py - real commands recorded with charmbracelet/vhs
Output demo/v2/build/{name}.mp4
Set Shell "bash"
Set FontSize 22
Set Width 1920
Set Height 1080
Set Padding 40
Set Theme "Catppuccin Mocha"
Set TypingSpeed 65ms
Hide
Type "cd {cd} && source .venv/bin/activate && export PYTHONPATH=src PS1='$ ' PYTHONWARNINGS=ignore {extra}&& clear" Enter
Sleep 1s
Show
'''


def tape(name, cd, steps, extra=""):
    out = HEAD.format(name=name, cd=cd, extra=extra)
    for step in steps:
        if step[0] == "clear":
            out += 'Type "clear" Enter\nSleep 300ms\n'
            continue
        if step[0] == "wait":  # block until the screen shows the regex, then hold
            _, regex, hold = step
            out += f"Wait+Screen@120s /{regex}/\nSleep {hold}\n"
            continue
        _, val, wait = step
        q = "`" if '"' in val else '"'
        if len(val) > PASTE_OVER:
            # Long command: appears at once, like a paste (realistic for long lines in a demo).
            out += f"Type@1ms {q}{val}{q}\nSleep 900ms\nEnter\nSleep {wait}\n"
        else:
            # Short command: typed at human speed, brief pause before Enter.
            out += f"Type {q}{val}{q}\nSleep 450ms\nEnter\nSleep {wait}\n"
    (HERE / "tapes" / f"{name}.tape").write_text(out)


